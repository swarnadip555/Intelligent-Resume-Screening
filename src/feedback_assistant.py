"""
Module: feedback_assistant.py
Implements Section 6 — GenAI Resume Feedback Assistant.

Features:
1. Systematic prompt construction aligning with HR Tech best practices.
2. Skill gap identification: highlights apparent matches and non-evidenced criteria.
3. Constructive recommendation generation.
4. Mandatory Responsible AI guardrails & disclaimers (decision-support only, no automated accept/reject).
5. Comprehensive prompt logging mechanism for auditability and compliance.
"""

import os
import json
import datetime


SYSTEM_PROMPT_TEMPLATE = """You are an objective, ethical HR decision-support assistant designed to assist human recruiters in evaluating resume alignment with job requirements.

STRICT ETHICAL GUIDELINES:
1. Decision Support Only: Do NOT make a final hiring decision or declare candidate accepted/rejected.
2. Fact-Based: Base your evaluation strictly on the candidate's explicitly stated skills and experience. Do NOT extrapolate or hallucinate unmentioned credentials.
3. Fairness & Neutrality: Never infer or consider protected demographic traits (gender, age, ethnicity, disability, location, etc.).
4. Constructive Feedback: Highlight evidenced strengths, identify skill/experience gaps, and provide actionable upskilling advice.

Provide output in the following structured format:
### Candidate Alignment Summary
- **Target Role**: {target_role}
- **Experience Match**: {experience_summary}

### Evidenced Strengths & Matching Skills
{matching_skills_list}

### Missing or Non-Evidenced Requirements
{missing_requirements_list}

### Actionable Upskilling Recommendations
{recommendations_list}

### Responsible AI Disclaimer
This evaluation was generated by an automated decision-support system. It represents textual alignment only and must NOT be used as an automatic hiring filter. A human recruiter must review the full candidate profile in context.
"""


def generate_feedback(candidate_data, job_data, log_path="reports/genai_prompt_log.json"):
    """
    Evaluates candidate profile against job description and creates structured feedback.
    Logs prompt and response to disk.
    """
    candidate_id = candidate_data.get("candidate_id", "Unknown")
    resume_text = candidate_data.get("resume_text", "")
    years_exp = candidate_data.get("years_experience", 0)
    cand_skills = [s.strip() for s in candidate_data.get("skills", "").split(";") if s.strip()]

    target_role = job_data.get("title", "Open Role")
    job_desc = job_data.get("description", "")
    req_skills = job_data.get("required_skills", [])
    min_exp = job_data.get("min_experience_years", 2)

    # Compute matches and gaps
    cand_skills_lower = {s.lower(): s for s in cand_skills}
    resume_lower = resume_text.lower()

    matched_skills = []
    missing_skills = []

    for req in req_skills:
        req_l = req.lower()
        if req_l in cand_skills_lower or req_l in resume_lower:
            matched_skills.append(req)
        else:
            missing_skills.append(req)

    # Experience evaluation
    if years_exp >= min_exp:
        exp_summary = f"Candidate has {years_exp} years of relevant experience, satisfying the requirement of {min_exp}+ years."
    else:
        exp_summary = f"Candidate has {years_exp} years of experience, which is below the benchmark requirement of {min_exp}+ years."

    matching_str = "\n".join([f"- **{s}**: Evidenced in candidate profile." for s in matched_skills]) if matched_skills else "- No direct matches for specified core skills."
    missing_str = "\n".join([f"- **{s}**: Not explicitly stated or evidenced in the resume text." for s in missing_skills]) if missing_skills else "- No significant skill gaps detected based on key requirements."

    recs = []
    if missing_skills:
        recs.append(f"Consider acquiring certifications or demonstrating hands-on project portfolio work in {', '.join(missing_skills)}.")
    if years_exp < min_exp:
        recs.append(f"Highlight transferable project achievements or intensive capstone deliverables to compensate for the {min_exp - years_exp}-year experience gap.")
    if not recs:
        recs.append("Candidate strongly reflects required skills. Recommend proceeding to technical recruiter screening interview.")

    recs_str = "\n".join([f"- {r}" for r in recs])

    feedback_text = SYSTEM_PROMPT_TEMPLATE.format(
        target_role=target_role,
        experience_summary=exp_summary,
        matching_skills_list=matching_str,
        missing_requirements_list=missing_str,
        recommendations_list=recs_str
    )

    log_entry = {
        "timestamp": datetime.datetime.now().isoformat(),
        "candidate_id": candidate_id,
        "target_role": target_role,
        "years_experience": years_exp,
        "min_experience_required": min_exp,
        "candidate_skills": cand_skills,
        "required_skills": req_skills,
        "matched_skills": matched_skills,
        "missing_skills": missing_skills,
        "generated_feedback": feedback_text
    }

    if log_path:
        os.makedirs(os.path.dirname(log_path), exist_ok=True)
        logs = []
        if os.path.exists(log_path):
            try:
                with open(log_path, "r", encoding="utf-8") as f:
                    logs = json.load(f)
            except Exception:
                logs = []
        logs.append(log_entry)
        with open(log_path, "w", encoding="utf-8") as f:
            json.dump(logs, f, indent=2)

    return feedback_text, log_entry
